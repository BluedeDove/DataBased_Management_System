// 性别比例（男性占比）
export const MALE_RATIO = 0.52

/**
 * 随机生成中文姓名
 * @param gender 性别 'male' | 'female' | 'random'
 * @returns 中文姓名
 */
export function generateChineseName(gender: 'male' | 'female' | 'random' = 'random'): string {
  const surname = SURNAMES[Math.floor(Math.random() * SURNAMES.length)]

  const actualGender = gender === 'random'
    ? (Math.random() < MALE_RATIO ? 'male' : 'female')
    : gender

  // 70% 双字名，30% 单字名
  const isDoubleName = Math.random() < 0.7

  if (actualGender === 'male') {
    if (isDoubleName) {
      return surname + MALE_NAMES_DOUBLE[Math.floor(Math.random() * MALE_NAMES_DOUBLE.length)]
    } else {
      return surname + MALE_NAMES_SINGLE[Math.floor(Math.random() * MALE_NAMES_SINGLE.length)]
    }
  } else {
    if (isDoubleName) {
      return surname + FEMALE_NAMES_DOUBLE[Math.floor(Math.random() * FEMALE_NAMES_DOUBLE.length)]
    } else {
      return surname + FEMALE_NAMES_SINGLE[Math.floor(Math.random() * FEMALE_NAMES_SINGLE.length)]
    }
  }
}

